const DICTS: Record<UILang, Record<string, string>> = { zh, en };

/** 翻译：zh 缺 key 回落 en 再回落 key 本身；params 做 {name} 简单插值。 */
export function translate(lang: UILang, key: string, params?: Record<string, string>): string {
  let text = DICTS[lang]?.[key] ?? DICTS.en[key] ?? key;
  if (params) {
    for (const [name, value] of Object.entries(params)) {
      text = text.split(`{${name}}`).join(value);
    }
  }
  return text;
}

